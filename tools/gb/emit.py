"""Emit a re-assemblable RGBDS source tree from an analysis result.

Guarantees, per bank, in this order:

1. every byte of the bank is emitted exactly once,
2. code is emitted as instructions when the walker proved it decodes,
3. everything else is emitted as ``db`` with the same bytes,
4. labels are emitted for every jump/call target and every referenced word.

Together those make ``build/`` reproduce the original ROM byte-for-byte,
which the ``verify`` subcommand checks.
"""

from __future__ import annotations

import re
from pathlib import Path

from .analyze import BankAnalysis
from .rom import Rom

HEX = "$%02x"

#: RGBDS section placement per bank.  The linker script reproduces the ROM's
#: cartridge layout, so one section per bank placed at its natural address is
#: enough for a byte-exact rebuild.
def section_for(bank: int) -> str:
    if bank == 0:
        return 'SECTION "bank00", ROM0'
    return f'SECTION "bank{bank:02d}", ROMX, BANK[{bank}]'


def _label(bank: int, addr: int, prefix: str, names: dict[str, str] | None) -> str:
    if names and f"{addr:04x}" in names and names[f"{addr:04x}"]:
        return names[f"{addr:04x}"]
    return f"{prefix}{bank:02d}_{addr:04x}" if bank else f"{prefix}{addr:04x}"


def _rgbds_text(text: str) -> str:
    """Rewrite our canonical mnemonics into RGBDS-accepted syntax."""
    t = text
    if t.startswith("cb "):
        t = t[3:]
    t = t.replace("[hli]", "[hl+]").replace("[hld]", "[hl-]")
    t = t.replace("ld [c],a", "ldh [c],a").replace("ld a,[c]", "ldh a,[c]")
    return t


_REL_OPS = frozenset({0x18, 0x20, 0x28, 0x30, 0x38})

#: Operands that reference another ROM address and must become label refs so
#: the source stays relocatable-safe (and readable).
_ABS_OPS = frozenset({0xC2, 0xC3, 0xC4, 0xCA, 0xCC, 0xCD, 0xD2, 0xD4,
                      0xDA, 0xDC})


def resolve_rel(ins, bank: int, cpu: int,
                names: dict[str, str] | None) -> str:
    """Render a relative jump as a label reference instead of a raw offset.

    RGBDS treats a bare number in ``jr`` as an absolute address, so the raw
    ``jr -5`` we decoded would be read as "jump to address -5".  Resolving to
    the target's label is also what keeps the rebuild stable if anything
    before the jump ever shifts.
    """
    rel = ins.operand or 0
    delta = rel - 0x100 if rel > 0x7F else rel
    target = cpu + ins.size + delta
    # jr nz / jr z / jr nc / jr c keep their condition; plain jr has none
    if "," in ins.text:
        cond = ins.text[3:].split(",")[0]
        return f"jr {cond},{_label(bank, target, 'sub_', names)}"
    return f"jr {_label(bank, target, 'sub_', names)}"


def resolve_abs(ins, bank: int, names: dict[str, str] | None) -> str:
    """Point ``jp``/``call`` at a label when the target is in this bank.

    Targets in the $4000-$7FFF window reached from bank 0 are ambiguous (that
    window can be any bank), so they stay numeric until the bank is known.
    """
    target = ins.operand or 0
    win = (0x0000, 0x3FFF) if bank == 0 else (0x4000, 0x7FFF)
    if win[0] <= target <= win[1]:
        head = ins.text.split(" ", 1)[0]
        cond = ins.text[3:].split(",")[0] if "," in ins.text else ""
        mnem = f"{head} {cond}," if cond else head
        return f"{mnem} {_label(bank, target, 'sub_', names)}"
    return ins.text


def _chunk_bytes(raw: bytes, start: int) -> list[str]:
    lines = []
    for i in range(0, len(raw), 16):
        piece = raw[i:i + 16]
        values = ",".join(f"${b:02x}" for b in piece)
        ascii_hint = "".join(chr(b) if 32 <= b < 127 else "." for b in piece)
        lines.append(f"    db {values}  ; {ascii_hint}")
    return lines


def emit_bank(rom: Rom, res: BankAnalysis, names: dict[str, str] | None = None,
              annotate: dict[str, str] | None = None) -> str:
    bank = res.bank
    base = 0 if bank == 0 else bank * 0x4000
    raw = rom.data[base:base + 0x4000]
    win_start = 0x0000 if bank == 0 else 0x4000

    out: list[str] = []
    title = f"bank {bank:02d} of {rom.header.title}"
    out.append(f"; {title} - {res.code_bytes()} bytes code "
               f"({res.coverage():.1%}), {len(res.code)} instructions")
    out.append("; generated by build.py from tools/gb/emit.py - do not hand-edit")
    out.append("")
    out.append(section_for(bank))
    out.append("")

    emitted: set[int] = set()
    code_starts = set(res.code)

    def emit_data(off: int, upto: int) -> None:
        nonlocal out
        while off < upto:
            # stop the run at the next label so labels stay addressable
            stop = upto
            for probe in range(off + 1, upto):
                cpu = win_start + probe
                if cpu in res.labels or cpu in res.all_refs:
                    stop = probe
                    break
            chunk = raw[off:stop]
            cpu = win_start + off
            out.append(f"{_label(bank, cpu, 'data_', names)}:")
            if annotate and f"{cpu:04x}" in annotate:
                out.append(f"    ; {annotate[f'{cpu:04x}']}")
            out.extend(_chunk_bytes(chunk, off))
            emitted.update(range(off, stop))
            off = stop

    off = 0
    size = len(raw)
    while off < size:
        cpu = win_start + off
        if cpu in res.labels and cpu not in code_starts:
            # a referenced address that the walker never proved is code
            out.append(f"{_label(bank, cpu, 'data_', names)}:")
        if off in res.code:
            ins = res.code[off]
            out.append(f"{_label(bank, cpu, 'sub_', names)}:")
            if annotate and f"{cpu:04x}" in annotate:
                out.append(f"    ; {annotate[f'{cpu:04x}']}")
            text = _rgbds_text(ins.text)
            if ins.op in _REL_OPS:
                text = resolve_rel(ins, bank, cpu, names)
            elif ins.op in _ABS_OPS:
                text = resolve_abs(ins, bank, names)
            out.append(f"    {text}")
            emitted.update(range(off, off + ins.size))
            off += ins.size
            continue

        # gather the largest data run up to the next instruction start / label
        run_end = off
        while run_end < size:
            c = win_start + run_end
            if run_end in res.code:
                break
            if run_end != off and c in res.labels:
                break
            run_end += 1
        emit_data(off, run_end)
        off = run_end

    return "\n".join(out) + "\n"


def emit_all(rom: Rom, results: dict[int, BankAnalysis],
             outdir: str | Path, codemap: dict | None = None) -> Path:
    outdir = Path(outdir)
    (outdir / "banks").mkdir(parents=True, exist_ok=True)

    names_by_bank = (codemap or {}).get("names", {})
    annotate_by_bank = (codemap or {}).get("comments", {})

    includes = []
    for bank in range(rom.nbanks):
        res = results.get(bank)
        if res is None:
            continue
        names = names_by_bank.get(str(bank))
        annot = annotate_by_bank.get(str(bank))
        text = emit_bank(rom, res, names, annot)
        path = outdir / "banks" / f"bank{bank:02d}.asm"
        path.write_text(text)
        includes.append(f'INCLUDE "banks/bank{bank:02d}.asm"')

    main = ["; generated by build.py - do not hand-edit", ""] + includes + [""]
    (outdir / "main.asm").write_text("\n".join(main))

    script = [f"; {rom.header.title} - {rom.nbanks} banks", ""]
    script.append("ROM0")
    script.append(f'  "bank00"')
    for bank in range(1, rom.nbanks):
        script.append(f"ROMX ${bank:02X}")
        script.append(f'  "bank{bank:02d}"')
    (outdir / "link.script").write_text("\n".join(script) + "\n")
    return outdir


